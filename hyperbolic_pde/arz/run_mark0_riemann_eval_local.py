"""Local launcher for arz_orig_paper_eval on the EXACT-RIEMANN dataset.

Same setup as run_mark0_paper_eval_local.py (HypNO-orig vs FNO vs Godunov vs
WENO5) but on a locally generated exact-Riemann ARZ dataset instead of the
homogeneous multi-discontinuity one. Uses the epoch-100 Riemann checkpoint.

The Riemann dataset is generated by datagen_arz with --exact-riemann-only; if
arz_riemann_local.npz is missing, regenerate it with:

    python -m hyperbolic_pde.arz.datagen_arz \
        --out hyperbolic_pde/arz/data/arz_riemann_local.npz \
        --N 100 --nx 128 --nt 128 --x-min -1 --x-max 1 --t-max 1.0 \
        --exact-riemann-only --stratified-riemann --pressure-form rho \
        --v-min 0.1 --v-max 0.9 --seed 0

Usage:
    python hyperbolic_pde/arz/run_mark0_riemann_eval_local.py
    python hyperbolic_pde/arz/run_mark0_riemann_eval_local.py --n-samples 20 --n-plots 5
"""
from __future__ import annotations
import argparse
import subprocess
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]

# ── edit these paths ──────────────────────────────────────────────────────────
CKPT = REPO / "hyperbolic_pde/runs/checkpoint_epoch100.pt"
DATA_RIEMANN = REPO / "hyperbolic_pde/arz/data/arz_riemann_local.npz"
# HypNO architecture config (saved alongside the epoch-100 checkpoint).
HYPNO_CONFIG = REPO / "hyperbolic_pde/runs/ckpt_100_cfg.yaml"
FNO_WEIGHTS = REPO / "hyperbolic_pde/arz/runs/fno_arz_local/fno_arz_bigger.pt"
# FNO architecture config: fno_arz_bigger.pt was trained with the `fno_arz`
# section of this yaml (its save_path matches the weights file). No Riemann-
# specific FNO exists, so we reuse the same weights as the homog eval.
FNO_CONFIG = REPO / "hyperbolic_pde/configs/hyperbolic_pde_arz.yaml"
OUT_DIR = REPO / "hyperbolic_pde/arz/runs/mark0_riemann_eval"
# ─────────────────────────────────────────────────────────────────────────────

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--ckpt", type=Path, default=CKPT)
    ap.add_argument("--data", type=Path, default=DATA_RIEMANN)
    ap.add_argument("--fno-weights", type=Path, default=FNO_WEIGHTS)
    ap.add_argument("--out-dir", type=Path, default=OUT_DIR)
    ap.add_argument("--n-samples", type=int, default=100)
    ap.add_argument("--n-plots", type=int, default=10)
    ap.add_argument("--baselines", type=str, default="godunov,weno5")
    ap.add_argument("--no-fno", action="store_true",
                    help="Skip FNO even if weights exist.")
    args = ap.parse_args()

    cmd = [
        sys.executable, "-m", "hyperbolic_pde.arz.arz_orig_paper_eval",
        "--ckpt", str(args.ckpt),
        "--config", str(HYPNO_CONFIG),
        "--model-section", "hypno_arz_orig",
        "--riemann-data", str(args.data),
        "--fno-config", str(FNO_CONFIG),
        "--fno-section", "fno_arz",
        "--baselines", args.baselines,
        "--n-samples", str(args.n_samples),
        "--n-plots", str(args.n_plots),
        "--out_dir", str(args.out_dir),
    ]

    if not args.no_fno and args.fno_weights.exists():
        cmd += ["--fno-weights", str(args.fno_weights)]
    elif not args.no_fno:
        print(f"[warn] FNO weights not found at {args.fno_weights} -- skipping FNO column")

    print("Running:", " ".join(cmd))
    subprocess.run(cmd, cwd=str(REPO), check=True)

if __name__ == "__main__":
    main()
